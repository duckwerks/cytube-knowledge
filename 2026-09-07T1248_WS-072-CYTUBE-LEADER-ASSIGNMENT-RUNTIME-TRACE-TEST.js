/*****************************************************************************************
 * WS-072 — CYTUBE LEADER ASSIGNMENT RUNTIME TRACE TEST
 *
 * PURPOSE
 * -------
 * This test performs a CONTROLLED runtime observation of CyTube's leader
 * assignment mechanism.
 *
 * We have already established from WS-071 that the client-side source contains:
 *
 *     socket.emit("assignLeader", { name: name })
 *
 * and that the client has an inbound callback:
 *
 *     setLeader(name)
 *
 * which ultimately updates:
 *
 *     CLIENT.leader
 *
 * WS-072 attempts to connect those two pieces at runtime:
 *
 *
 *     USER CLICKS "GIVE LEADER" / "REMOVE LEADER"
 *                         |
 *                         v
 *                 socket.emit(...)
 *                         |
 *                         v
 *                    SERVER
 *                         |
 *                         v
 *                  setLeader(name)
 *                         |
 *                         v
 *                 CLIENT.leader
 *
 *
 * IMPORTANT
 * ---------
 * This test DOES NOT initiate assignLeader itself.
 *
 * The actual administrative action must be performed manually through the
 * normal CyTube UI.
 *
 * This is intentional.
 *
 * We want to observe the application's real behavior rather than manufacture
 * a protocol message ourselves.
 *
 *
 * WHAT THIS TEST CAN PROVE
 * ------------------------
 *
 * If the user has sufficient permission and performs one leader action, we
 * should be able to establish:
 *
 *   1. The UI action causes a real outbound assignLeader event.
 *
 *   2. The exact payload sent by the client.
 *
 *   3. Whether CyTube subsequently delivers setLeader to this client.
 *
 *   4. The exact argument supplied to setLeader.
 *
 *   5. Whether CLIENT.leader changes.
 *
 *   6. Whether the userlist / leader UI changes at approximately the same time.
 *
 *
 * WHAT THIS TEST CANNOT PROVE BY ITSELF
 * -------------------------------------
 *
 * It cannot inspect the private server implementation.
 *
 * Therefore:
 *
 *   assignLeader observed
 *       !=
 *   server authorization rules proven
 *
 * We can prove that the browser sent the command.
 *
 * We can prove whether this client subsequently received the corresponding
 * setLeader state update.
 *
 * That gives us strong end-to-end behavioral evidence, but not the actual
 * server-side authorization source code.
 *
 *
 * MOBILE / DEVTOOLS DESIGN
 * ------------------------
 *
 * The test deliberately stores its final result in:
 *
 *     window.__WS072_DATA__
 *
 * The separate synchronous copy command at the bottom should be executed
 * manually AFTER the test finishes.
 *
 * This follows the mobile DevTools clipboard behavior already established:
 *
 *     asynchronous clipboard operations are unreliable,
 *     synchronous copy(JSON.stringify(...)) works.
 *
 *
 * SAFETY / SCOPE
 * --------------
 *
 * - No automatic leader assignment.
 * - No automatic leader removal.
 * - No playlist modification.
 * - No chat messages.
 * - No server commands generated by this script.
 * - Only temporary wrappers around existing client functions.
 *
 *****************************************************************************************/

(async function WS072() {

    const TEST_NAME = "WS-072";

    /*************************************************************************************
     * TEST CONFIGURATION
     *************************************************************************************/

    const CONFIG = {

        /*
         * How long we leave the instrumentation installed.
         *
         * This is intentionally much shorter than the previous 60-second
         * passive observation tests because this is a controlled action test.
         *
         * You should perform exactly ONE leader action during this window.
         */
        timeoutMs: 60000,

        /*
         * Maximum number of recorded events of each category.
         *
         * This prevents an unexpectedly noisy page from producing an enormous
         * artifact.
         */
        maxEvents: 100,

        /*
         * Whether to capture selected DOM snapshots.
         */
        captureDOM: true
    };


    /*************************************************************************************
     * BASIC RUNTIME SNAPSHOT
     *************************************************************************************/

    const startedAt = new Date().toISOString();

    const DATA = {

        test: TEST_NAME,

        status: "STARTING",

        startedAt: startedAt,

        completedAt: null,

        instructions: {
            action:
                "Perform exactly ONE normal CyTube leader action using the UI: " +
                "Give Leader OR Remove Leader, if your account has permission.",
            doNot:
                "Do not perform additional leader actions during this test window.",
            expected:
                "An outbound assignLeader event should appear if the UI action is accepted locally."
        },

        page: {
            url: location.href,
            title: document.title,
            readyState: document.readyState,
            timestamp: startedAt
        },

        runtime: {

            windowExists: typeof window !== "undefined",

            socketExists: !!window.socket,

            socketConnected: !!window.socket?.connected,

            callbacksExists: !!window.Callbacks,

            clientExists: !!window.CLIENT,

            channelExists: !!window.CHANNEL,

            channelName: window.CHANNEL?.name ?? null,

            clientName: window.CLIENT?.name ?? null,

            clientRank:
                typeof window.CLIENT?.rank === "number"
                    ? window.CLIENT.rank
                    : null,

            clientLeader:
                typeof window.CLIENT?.leader !== "undefined"
                    ? window.CLIENT.leader
                    : null,

            leaderctlPermission:
                typeof window.CHANNEL?.perms?.leaderctl !== "undefined"
                    ? window.CHANNEL.perms.leaderctl
                    : null,

            hasLeaderctl:
                typeof window.hasPermission === "function"
                    ? safeHasPermission("leaderctl")
                    : null
        },

        events: [],

        outboundAssignLeader: [],

        inboundSetLeader: [],

        leaderTransitions: [],

        domSnapshots: [],

        errors: [],

        restoration: {

            socketEmitRestored: false,

            setLeaderRestored: false,

            completed: false
        }
    };


    /*************************************************************************************
     * SAFE HELPER
     *
     * CyTube's runtime objects are live application state. We do not want a
     * diagnostic helper itself to crash the test.
     *************************************************************************************/

    function safeHasPermission(key) {

        try {

            return !!window.hasPermission(key);

        } catch (e) {

            DATA.errors.push({
                stage: "hasPermission",
                message: String(e),
                stack: e?.stack || null,
                timestamp: new Date().toISOString()
            });

            return null;
        }
    }


    /*************************************************************************************
     * SAFE SERIALIZATION
     *
     * Socket.IO payloads can contain objects that are awkward to stringify.
     * This helper attempts JSON serialization while protecting the test from
     * circular structures.
     *************************************************************************************/

    function safeClone(value) {

        try {

            return JSON.parse(JSON.stringify(value));

        } catch (e) {

            try {

                return String(value);

            } catch (_) {

                return "[Unserializable value]";
            }
        }
    }


    /*************************************************************************************
     * EVENT RECORDER
     *************************************************************************************/

    function record(array, item) {

        if (array.length >= CONFIG.maxEvents) {

            return;
        }

        array.push(item);
    }


    /*************************************************************************************
     * DOM SNAPSHOT
     *
     * The purpose here is not to reverse-engineer the entire userlist.
     *
     * We only want enough evidence to determine whether a visible user/leader
     * state changed around the same time as setLeader().
     *************************************************************************************/

    function captureDOMSnapshot(reason) {

        if (!CONFIG.captureDOM) {

            return;
        }

        try {

            const users = [];

            /*
             * CyTube userlist entries can vary somewhat with UI version/theme.
             *
             * We therefore inspect common userlist containers rather than
             * depending on one exact selector.
             */

            const candidates = document.querySelectorAll(
                "#userlist li, #userlist .userlist_entry, .userlist_entry, .user"
            );

            for (const el of candidates) {

                if (users.length >= 100) {
                    break;
                }

                const text = (el.innerText || el.textContent || "")
                    .replace(/\s+/g, " ")
                    .trim();

                if (!text) {
                    continue;
                }

                users.push({
                    text: text.slice(0, 300),

                    className:
                        typeof el.className === "string"
                            ? el.className
                            : "",

                    title:
                        el.getAttribute?.("title") || null,

                    dataName:
                        el.getAttribute?.("data-name") || null,

                    dataRank:
                        el.getAttribute?.("data-rank") || null,

                    dataLeader:
                        el.getAttribute?.("data-leader") || null
                });
            }

            record(DATA.domSnapshots, {

                timestamp: new Date().toISOString(),

                reason: reason,

                clientLeader:
                    typeof window.CLIENT?.leader !== "undefined"
                        ? window.CLIENT.leader
                        : null,

                users: users
            });

        } catch (e) {

            DATA.errors.push({

                stage: "captureDOMSnapshot",

                message: String(e),

                stack: e?.stack || null,

                timestamp: new Date().toISOString()
            });
        }
    }


    /*************************************************************************************
     * PRECONDITION CHECK
     *************************************************************************************/

    if (!window.socket) {

        DATA.status = "ABORTED_NO_SOCKET";

        DATA.errors.push({

            stage: "precondition",

            message: "window.socket does not exist.",

            timestamp: new Date().toISOString()
        });

        window.__WS072_DATA__ = DATA;

        console.error("WS-072 aborted: window.socket does not exist.");

        return;
    }


    if (!window.socket.connected) {

        DATA.status = "ABORTED_SOCKET_NOT_CONNECTED";

        DATA.errors.push({

            stage: "precondition",

            message: "window.socket exists but is not connected.",

            timestamp: new Date().toISOString()
        });

        window.__WS072_DATA__ = DATA;

        console.error("WS-072 aborted: socket is not connected.");

        return;
    }


    if (!window.Callbacks) {

        DATA.status = "ABORTED_NO_CALLBACKS";

        DATA.errors.push({

            stage: "precondition",

            message: "window.Callbacks does not exist.",

            timestamp: new Date().toISOString()
        });

        window.__WS072_DATA__ = DATA;

        console.error("WS-072 aborted: window.Callbacks does not exist.");

        return;
    }


    if (typeof window.Callbacks.setLeader !== "function") {

        DATA.status = "ABORTED_NO_SETLEADER";

        DATA.errors.push({

            stage: "precondition",

            message: "Callbacks.setLeader is not a function.",

            timestamp: new Date().toISOString()
        });

        window.__WS072_DATA__ = DATA;

        console.error("WS-072 aborted: Callbacks.setLeader unavailable.");

        return;
    }


    /*************************************************************************************
     * CAPTURE ORIGINAL FUNCTIONS
     *
     * We MUST preserve the original functions so they can be restored exactly
     * when the test ends.
     *************************************************************************************/

    const originalSocketEmit = window.socket.emit;

    const originalSetLeader = window.Callbacks.setLeader;


    /*************************************************************************************
     * UNIQUE TEST TOKEN
     *
     * This is diagnostic metadata only.
     *
     * We do NOT send it to the server.
     *************************************************************************************/

    const testInstance =
        "WS072-" +
        Date.now() +
        "-" +
        Math.random().toString(36).slice(2, 8);


    DATA.testInstance = testInstance;


    /*************************************************************************************
     * INITIAL SNAPSHOT
     *************************************************************************************/

    DATA.initial = {

        timestamp: new Date().toISOString(),

        clientName: window.CLIENT?.name ?? null,

        clientRank:
            typeof window.CLIENT?.rank === "number"
                ? window.CLIENT.rank
                : null,

        clientLeader:
            typeof window.CLIENT?.leader !== "undefined"
                ? window.CLIENT.leader
                : null,

        leaderctlPermission:
            window.CHANNEL?.perms?.leaderctl ?? null,

        hasLeaderctl:
            safeHasPermission("leaderctl")
    };


    captureDOMSnapshot("initial");


    /*************************************************************************************
     * WRAP socket.emit()
     *
     * This is the most important outbound observation.
     *
     * We do NOT alter arguments.
     *
     * We simply record them and then call the original function with exactly
     * the same this-value and arguments.
     *
     * Therefore:
     *
     *     application
     *          |
     *          v
     *     wrapped emit
     *          |
     *          +----> diagnostic record
     *          |
     *          v
     *     original socket.emit
     *          |
     *          v
     *        server
     *
     *************************************************************************************/

    window.socket.emit = function WS072_socket_emit_wrapper(...args) {

        const timestamp = new Date().toISOString();

        const eventName =
            typeof args[0] === "string"
                ? args[0]
                : null;

        const entry = {

            timestamp: timestamp,

            event: eventName,

            argCount: args.length,

            args: safeClone(args),

            clientLeader:
                typeof window.CLIENT?.leader !== "undefined"
                    ? window.CLIENT.leader
                    : null,

            clientName:
                window.CLIENT?.name ?? null
        };


        /*
         * Record ALL outbound events while the test is running, but separately
         * index assignLeader because that is our primary target.
         */

        record(DATA.events, {

            direction: "outbound",

            ...entry
        });


        if (eventName === "assignLeader") {

            record(DATA.outboundAssignLeader, entry);

            console.log(
                "WS-072 OUTBOUND assignLeader:",
                safeClone(args)
            );
        }


        /*
         * Preserve exact application behavior.
         */

        return originalSocketEmit.apply(this, args);
    };


    /*************************************************************************************
     * WRAP Callbacks.setLeader()
     *
     * This observes the point where CyTube's generic Socket.IO callback
     * dispatcher reaches the application's setLeader handler.
     *
     * Recall the established architecture:
     *
     *     socket.on("setLeader", function(data) {
     *         Callbacks["setLeader"](data);
     *     });
     *
     * By wrapping Callbacks.setLeader we therefore observe the callback after
     * Socket.IO has delivered the event to the browser.
     *************************************************************************************/

    window.Callbacks.setLeader = function WS072_setLeader_wrapper(...args) {

        const timestamp = new Date().toISOString();

        const beforeLeader =
            typeof window.CLIENT?.leader !== "undefined"
                ? window.CLIENT.leader
                : null;


        const entry = {

            timestamp: timestamp,

            callback: "setLeader",

            argCount: args.length,

            args: safeClone(args),

            CLIENT_leader_before: beforeLeader,

            CLIENT_name:
                window.CLIENT?.name ?? null,

            CLIENT_rank:
                typeof window.CLIENT?.rank === "number"
                    ? window.CLIENT.rank
                    : null
        };


        record(DATA.inboundSetLeader, entry);

        record(DATA.events, {

            direction: "inbound-callback",

            ...entry
        });


        console.log(
            "WS-072 INBOUND setLeader:",
            safeClone(args)
        );


        /*
         * Execute the REAL CyTube setLeader callback.
         */

        let result;

        try {

            result = originalSetLeader.apply(this, args);

        } catch (e) {

            DATA.errors.push({

                stage: "originalSetLeader",

                message: String(e),

                stack: e?.stack || null,

                timestamp: new Date().toISOString()
            });

            throw e;
        }


        /*
         * Capture state immediately after the real callback executes.
         */

        const afterLeader =
            typeof window.CLIENT?.leader !== "undefined"
                ? window.CLIENT.leader
                : null;


        entry.CLIENT_leader_after = afterLeader;


        if (beforeLeader !== afterLeader) {

            record(DATA.leaderTransitions, {

                timestamp: new Date().toISOString(),

                before: beforeLeader,

                after: afterLeader,

                setLeaderArgs: safeClone(args)
            });


            console.log(
                "WS-072 CLIENT.leader transition:",
                beforeLeader,
                "→",
                afterLeader
            );
        }


        captureDOMSnapshot("after setLeader");


        return result;
    };


    /*************************************************************************************
     * TEST IS NOW ARMED
     *************************************************************************************/

    DATA.status = "ARMED";

    DATA.armedAt = new Date().toISOString();


    window.__WS072_DATA__ = DATA;


    console.log(
        "============================================================"
    );

    console.log(
        "WS-072 — CYTUBE LEADER ASSIGNMENT RUNTIME TRACE"
    );

    console.log(
        "============================================================"
    );

    console.log(
        "Instrumentation installed."
    );

    console.log(
        "Client:",
        window.CLIENT?.name
    );

    console.log(
        "Rank:",
        window.CLIENT?.rank
    );

    console.log(
        "Current leader:",
        window.CLIENT?.leader
    );

    console.log(
        "leaderctl permission:",
        window.CHANNEL?.perms?.leaderctl
    );

    console.log(
        "hasPermission('leaderctl'):",
        safeHasPermission("leaderctl")
    );

    console.log(
        ""
    );

    console.log(
        ">>> NOW PERFORM EXACTLY ONE NORMAL LEADER ACTION."
    );

    console.log(
        ">>> Use Give Leader OR Remove Leader if available."
    );

    console.log(
        ">>> Do not perform additional leader actions."
    );

    console.log(
        ">>> The test will automatically finish after",
        CONFIG.timeoutMs / 1000,
        "seconds."
    );

    console.log(
        "============================================================"
    );


    /*************************************************************************************
     * WAIT FOR CONTROLLED ACTION
     *************************************************************************************/

    await new Promise(resolve => {

        setTimeout(resolve, CONFIG.timeoutMs);

    });


    /*************************************************************************************
     * RESTORE socket.emit
     *************************************************************************************/

    try {

        if (window.socket.emit === window.socket.emit) {
            /*
             * The identity comparison above is intentionally harmless.
             *
             * We restore the function unconditionally because this test owns
             * the wrapper during its execution window.
             */
        }

        window.socket.emit = originalSocketEmit;

        DATA.restoration.socketEmitRestored = true;

    } catch (e) {

        DATA.errors.push({

            stage: "restore socket.emit",

            message: String(e),

            stack: e?.stack || null,

            timestamp: new Date().toISOString()
        });
    }


    /*************************************************************************************
     * RESTORE setLeader
     *************************************************************************************/

    try {

        window.Callbacks.setLeader = originalSetLeader;

        DATA.restoration.setLeaderRestored = true;

    } catch (e) {

        DATA.errors.push({

            stage: "restore Callbacks.setLeader",

            message: String(e),

            stack: e?.stack || null,

            timestamp: new Date().toISOString()
        });
    }


    /*************************************************************************************
     * FINAL SNAPSHOT
     *************************************************************************************/

    captureDOMSnapshot("final");


    DATA.final = {

        timestamp: new Date().toISOString(),

        clientName:
            window.CLIENT?.name ?? null,

        clientRank:
            typeof window.CLIENT?.rank === "number"
                ? window.CLIENT.rank
                : null,

        clientLeader:
            typeof window.CLIENT?.leader !== "undefined"
                ? window.CLIENT.leader
                : null,

        outboundAssignLeaderCount:
            DATA.outboundAssignLeader.length,

        inboundSetLeaderCount:
            DATA.inboundSetLeader.length,

        leaderTransitionCount:
            DATA.leaderTransitions.length
    };


    /*************************************************************************************
     * INTERPRETATION FLAGS
     *
     * These are deliberately conservative.
     *************************************************************************************/

    DATA.interpretation = {

        outboundAssignLeaderObserved:
            DATA.outboundAssignLeader.length > 0,

        inboundSetLeaderObserved:
            DATA.inboundSetLeader.length > 0,

        clientLeaderChanged:
            DATA.leaderTransitions.length > 0,

        endToEndClientPathObserved:
            DATA.outboundAssignLeader.length > 0 &&
            DATA.inboundSetLeader.length > 0,

        serverAcceptanceInferred:
            DATA.outboundAssignLeader.length > 0 &&
            DATA.inboundSetLeader.length > 0,

        serverSourceCodeProven:
            false,

        note:
            "An outbound assignLeader followed by inbound setLeader is strong " +
            "runtime evidence of the client-to-server-to-client path, but does " +
            "not expose the server implementation itself."
    };


    /*************************************************************************************
     * FINAL STATUS
     *************************************************************************************/

    DATA.status = "COMPLETE";

    DATA.completedAt = new Date().toISOString();

    DATA.restoration.completed =
        DATA.restoration.socketEmitRestored &&
        DATA.restoration.setLeaderRestored;


    /*
     * Re-publish the completed artifact.
     */

    window.__WS072_DATA__ = DATA;


    /*************************************************************************************
     * FINAL CONSOLE SUMMARY
     *************************************************************************************/

    console.log(
        "============================================================"
    );

    console.log(
        "WS-072 COMPLETE"
    );

    console.log(
        "============================================================"
    );

    console.log(
        "Outbound assignLeader:",
        DATA.outboundAssignLeader.length
    );

    console.log(
        "Inbound setLeader:",
        DATA.inboundSetLeader.length
    );

    console.log(
        "CLIENT.leader transitions:",
        DATA.leaderTransitions.length
    );

    console.log(
        "End-to-end client path observed:",
        DATA.interpretation.endToEndClientPathObserved
    );

    console.log(
        "Instrumentation restored:",
        DATA.restoration.completed
    );

    console.log(
        "Full result stored in window.__WS072_DATA__"
    );

    console.log(
        "============================================================"
    );

})();

